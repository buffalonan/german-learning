// Writes art.js, the list of card illustrations in art/<topic id>/<artName(german)>.webp,
// so the page knows which cards have one and which keep their emoji picture.
// Usage: node scripts/build-art.js (scripts/add-art.py runs it after adding pictures)
const fs = require("fs");
const path = require("path");

const root = path.join(__dirname, "..");
const dir = path.join(root, "art");
const names = [];
if (fs.existsSync(dir)) {
  for (const topic of fs.readdirSync(dir).sort()) {
    if (!fs.statSync(path.join(dir, topic)).isDirectory()) continue;
    for (const f of fs.readdirSync(path.join(dir, topic)).sort()) if (f.endsWith(".webp")) names.push(`${topic}/${f.slice(0, -5)}`);
  }
}
fs.writeFileSync(path.join(root, "art.js"), `// Generated by scripts/build-art.js. Don't edit by hand.\nwindow.ART = ${JSON.stringify(names, null, 1)};\n`);
console.log(`art.js lists ${names.length} illustrations`);
